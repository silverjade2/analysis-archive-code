def device_days_per_month(w: pd.DataFrame) -> pd.Series:
    """기기별 관측 구간 [obs_from, obs_to)를 달력월로 잘라 기기-일 합. w에는 obs_from, obs_to"""
    out = {}
    for m0 in pd.date_range(A_START.to_period("M").to_timestamp(), END, freq="MS"):
        m1 = m0 + pd.offsets.MonthBegin(1)
        lo = w["obs_from"].clip(lower=m0)
        hi = w["obs_to"].clip(upper=m1)
        out[m0] = float((hi - lo).dt.days.clip(lower=0).sum())
    return pd.Series(out, name="device_days")
