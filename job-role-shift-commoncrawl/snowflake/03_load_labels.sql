-- 업무 유형 라벨을 BIGDATA.TASK1 에 올린다. 01 을 먼저 실행 (파일 형식을 같이 쓴다)
-- 순서: 1단계 실행, TASK1_STAGE 에 label_pool.parquet, labels_agent.parquet 업로드, 2단계, 3단계 확인, dbt build
-- label_pool.parquet 는 공고 원문이라 저장소에 없다

-- 1. 위치, stage
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE BIGDATA_WH;
CREATE SCHEMA IF NOT EXISTS BIGDATA.TASK1;
USE SCHEMA BIGDATA.TASK1;
CREATE STAGE IF NOT EXISTS TASK1_STAGE
  FILE_FORMAT = BIGDATA.JOBKKO.PARQUET_FMT DIRECTORY = (ENABLE = TRUE) ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE');

LIST @TASK1_STAGE;

-- 2. 적재
-- 공고 묶음 (기대값 1271)
CREATE TABLE IF NOT EXISTS LABEL_POOL USING TEMPLATE (
  SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) WITHIN GROUP (ORDER BY ORDER_ID)
  FROM TABLE(INFER_SCHEMA(LOCATION => '@TASK1_STAGE', FILES => 'label_pool.parquet',
                          FILE_FORMAT => 'BIGDATA.JOBKKO.PARQUET_FMT', IGNORE_CASE => TRUE)));
COPY INTO LABEL_POOL FROM @TASK1_STAGE FILES = ('label_pool.parquet')
  FILE_FORMAT = (FORMAT_NAME = 'BIGDATA.JOBKKO.PARQUET_FMT') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

-- 라벨 (기대값 713)
CREATE OR REPLACE TABLE AGENT_LABELS USING TEMPLATE (
  SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) WITHIN GROUP (ORDER BY ORDER_ID)
  FROM TABLE(INFER_SCHEMA(LOCATION => '@TASK1_STAGE', FILES => 'labels_agent.parquet',
                          FILE_FORMAT => 'BIGDATA.JOBKKO.PARQUET_FMT', IGNORE_CASE => TRUE)));
COPY INTO AGENT_LABELS FROM @TASK1_STAGE FILES = ('labels_agent.parquet')
  FILE_FORMAT = (FORMAT_NAME = 'BIGDATA.JOBKKO.PARQUET_FMT') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE FORCE = TRUE;

-- 3. 확인
SELECT COUNT(*) AS POOL_ROWS FROM LABEL_POOL;                      -- 1271
SELECT COUNT(*) AS LABEL_ROWS, COUNT(OVERRIDE) AS OVERRIDES FROM AGENT_LABELS;  -- 713, 17
